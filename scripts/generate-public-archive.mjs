import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inventory = JSON.parse(fs.readFileSync(path.join(projectRoot, "research/inventory/content-inventory.json"), "utf8"));
const routeMap = JSON.parse(fs.readFileSync(path.join(projectRoot, "research/inventory/legacy-route-map.json"), "utf8"));
const mediaInventory = JSON.parse(fs.readFileSync(path.join(projectRoot, "research/inventory/media-inventory.json"), "utf8"));
const managedAssetRecords = JSON.parse(fs.readFileSync(path.join(projectRoot, "research/assets/managed-legacy-assets.json"), "utf8"));
const mediaById = new Map(mediaInventory.map(record => [record.id, record]));
const managedUrlBySource = new Map(managedAssetRecords.map(record => [record.legacy_source_url, record.managed_url]));

const entities = {
  amp: "&", quot: '"', apos: "'", nbsp: " ", hellip: "…", ndash: "–", mdash: "—",
  lsquo: "‘", rsquo: "’", ldquo: "“", rdquo: "”", bull: "•",
};

function decodeEntities(value = "") {
  return value
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, code) => String.fromCodePoint(Number.parseInt(code, 16)))
    .replace(/&([a-z]+);/gi, (match, name) => entities[name.toLowerCase()] ?? match);
}

function plain(value = "") {
  return decodeEntities(value.replace(/<[^>]*>/g, " ").replace(/\s+/g, " ")).trim();
}

function paragraphs(html = "", fallback = "") {
  const text = decodeEntities(html
    .replace(/<\s*br\s*\/?>/gi, "\n")
    .replace(/<\/(p|div|section|article|h[1-6]|li)>/gi, "\n\n")
    .replace(/<li[^>]*>/gi, "• ")
    .replace(/<[^>]*>/g, " "))
    .replace(/\u00a0/g, " ")
    .replace(/[ \t]+/g, " ")
    .replace(/\n[ \t]+/g, "\n")
    .trim();
  const result = text.split(/\n\s*\n+/).map(part => part.trim()).filter(Boolean);
  return result.length ? result : [plain(fallback)].filter(Boolean);
}

function managedUrl(url) {
  return managedUrlBySource.get(url) ?? url;
}

function transform(record) {
  const featuredMedia = mediaById.get(record.featured_media_id);
  return {
    id: record.id,
    type: record.type,
    title: plain(record.title),
    slug: record.slug,
    publishedAt: record.published_at,
    modifiedAt: record.modified_at,
    authorName: record.author_name || "IBAA",
    authorLegacyUrl: record.author_legacy_url || null,
    legacyUrl: record.legacy_url,
    destination: record.proposed_destination,
    categories: record.categories ?? [],
    tags: record.tags ?? [],
    excerpt: plain(record.excerpt) || paragraphs(record.content_html, record.plain_text)[0] || "Legacy IBAA archive record.",
    body: paragraphs(record.content_html, record.plain_text),
    featuredMediaUrl: record.featured_media_url ? managedUrl(record.featured_media_url) : null,
    featuredMediaAlt: plain(record.featured_media_alt) || null,
    featuredMediaCaption: plain(featuredMedia?.caption) || null,
    featuredMediaDescription: plain(featuredMedia?.description) || null,
    documentUrls: (record.document_urls ?? []).map(managedUrl),
    linkedUrls: record.linked_urls ?? [],
  };
}

const posts = inventory.filter(record => record.type === "post").map(transform).sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
const pages = inventory.filter(record => record.type === "page").map(transform).sort((a, b) => a.title.localeCompare(b.title));
const media = mediaInventory.map(record => ({
  id: record.id,
  title: plain(record.title) || record.slug,
  slug: record.slug,
  publishedAt: record.published_at,
  modifiedAt: record.modified_at,
  mediaType: record.media_type,
  mimeType: record.mime_type,
  sourceUrl: managedUrl(record.source_url),
  originalUploadUrl: record.original_upload_url || record.source_url,
  legacyAttachmentUrl: record.legacy_attachment_url,
  altText: plain(record.alt_text),
  caption: plain(record.caption),
  description: plain(record.description),
  width: record.width,
  height: record.height,
  fileSizeBytes: record.file_size_bytes,
})).sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
const redirectEntries = routeMap
  .map(record => {
    const legacyPath = new URL(record.legacy_url).pathname;
    return [legacyPath, { destination: record.destination, routeType: record.route_type }];
  })
  .filter(([legacyPath, value]) => legacyPath !== value.destination);

const archiveOutput = `// Generated by scripts/generate-public-archive.mjs. Do not edit manually.\n` +
  `export const legacyPosts = ${JSON.stringify(posts, null, 2)} as const;\n\n` +
  `export const legacyPages = ${JSON.stringify(pages, null, 2)} as const;\n\n` +
  `export const legacyMedia = ${JSON.stringify(media, null, 2)} as const;\n`;
const redirectsOutput = `// Generated by scripts/generate-public-archive.mjs. Do not edit manually.\n` +
  `export const legacyRedirects = new Map<string, { destination: string; routeType: string }>(${JSON.stringify(redirectEntries, null, 2)});\n`;
const coreRoutes = ["/", "/about", "/buddhist-traditions", "/leadership", "/annual-delegates", "/programs", "/programs/youth", "/study-circles", "/events", "/member-temples", "/news-media", "/resources", "/join", "/donate", "/contact"];
const sitemapRecords = new Map(coreRoutes.map(route => [route, null]));
for (const record of [...pages, ...posts]) {
  if (!record.destination.includes("?")) sitemapRecords.set(record.destination, record.modifiedAt || record.publishedAt);
}
const sitemapOutput = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  Array.from(sitemapRecords.entries()).sort(([a], [b]) => a.localeCompare(b)).map(([route, modified]) => {
    const location = `https://www.ibaa.org${route === "/" ? "/" : route}`;
    return `  <url><loc>${location}</loc>${modified ? `<lastmod>${modified.slice(0, 10)}</lastmod>` : ""}</url>`;
  }).join("\n") + `\n</urlset>\n`;

fs.mkdirSync(path.join(projectRoot, "client/src/data"), { recursive: true });
fs.writeFileSync(path.join(projectRoot, "client/src/data/legacyArchive.generated.ts"), archiveOutput);
fs.writeFileSync(path.join(projectRoot, "server/legacyRedirects.generated.ts"), redirectsOutput);
fs.writeFileSync(path.join(projectRoot, "client/public/sitemap.xml"), sitemapOutput);

console.log(JSON.stringify({ posts: posts.length, pages: pages.length, media: media.length, redirects: redirectEntries.length }));
