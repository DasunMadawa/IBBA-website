// Converts deployment/seed-current-public-content.sql (MySQL dialect) into
// deployment/seed-current-public-content.pg.sql for the PostgreSQL schema.
// Only SQL outside single-quoted string literals is rewritten, so content is untouched.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const source = path.resolve("deployment/seed-current-public-content.sql");
const target = path.resolve("deployment/seed-current-public-content.pg.sql");
const SEED_USER = `(SELECT id FROM users WHERE "openId"='staging:public-content-seed' LIMIT 1)`;

function splitLiterals(statement) {
  const parts = [];
  let code = "";
  for (let i = 0; i < statement.length; i++) {
    if (statement[i] !== "'") {
      code += statement[i];
      continue;
    }
    let end = i + 1;
    while (end < statement.length) {
      if (statement[end] === "'" && statement[end + 1] === "'") end += 2;
      else if (statement[end] === "'") break;
      else end++;
    }
    parts.push({ code }, { literal: statement.slice(i, end + 1) });
    code = "";
    i = end;
  }
  parts.push({ code });
  return parts;
}

function convertCode(code) {
  return code
    .replace(/`([^`]+)`/g, '"$1"')
    .replace(/\bVALUES\("([^"]+)"\)/g, 'EXCLUDED."$1"')
    .replace(/@seed_user_id/g, SEED_USER);
}

const explicitIdTables = new Set();
const output = [
  "-- Generated by scripts/convert-mysql-seed-to-pg.mjs from seed-current-public-content.sql. Do not edit by hand.",
];
for (const line of (await readFile(source, "utf8")).split(/\r?\n/)) {
  if (!line.trim() || line.startsWith("--")) {
    output.push(line);
    continue;
  }
  if (/^SET NAMES/i.test(line)) {
    output.push("SET client_encoding = 'UTF8';", "SET TIME ZONE 'UTC';");
    continue;
  }
  if (/^SET @seed_user_id/i.test(line)) continue;

  let sql = splitLiterals(line).map(part => part.literal ?? convertCode(part.code)).join("");
  if (/^INSERT INTO users \(/.test(sql)) {
    sql = sql
      .replace(/^INSERT INTO users \(([^)]*)\)/, (_, cols) => `INSERT INTO users (${cols.split(",").map(c => `"${c.trim()}"`).join(",")})`)
      .replace(/ON DUPLICATE KEY UPDATE name=VALUES\(name\)/, 'ON CONFLICT ("openId") DO UPDATE SET name=EXCLUDED.name');
  }
  if (/^INSERT IGNORE INTO/.test(sql)) {
    sql = sql.replace(/^INSERT IGNORE INTO/, "INSERT INTO").replace(/;\s*$/, " ON CONFLICT DO NOTHING;");
  }
  if (sql.includes("ON DUPLICATE KEY UPDATE")) {
    sql = sql.replace("ON DUPLICATE KEY UPDATE", 'ON CONFLICT ("id") DO UPDATE SET');
  }
  const table = sql.match(/^INSERT INTO "([a-z_]+)" \("id",/);
  if (table) explicitIdTables.add(table[1]);
  if (/^COMMIT;/.test(sql)) {
    // Explicit ids bypass the serial sequences; move them past the seeded rows.
    for (const name of explicitIdTables) {
      output.push(`SELECT setval(pg_get_serial_sequence('${name}', 'id'), (SELECT MAX(id) FROM "${name}"));`);
    }
  }
  if (/ON DUPLICATE KEY|INSERT IGNORE|`|@seed_user_id/.test(splitLiterals(sql).map(p => p.code ?? "").join(""))) {
    throw new Error(`Unconverted MySQL syntax remains: ${sql.slice(0, 160)}`);
  }
  output.push(sql);
}
await writeFile(target, output.join("\n"));
console.log(`Wrote ${path.relative(process.cwd(), target)} (sequences reset for: ${[...explicitIdTables].join(", ")}).`);
